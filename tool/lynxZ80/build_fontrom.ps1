$generatedSymbolMap = @{
    0xF1='円'; 0xF2='年'; 0xF3='月'; 0xF4='日'; 0xF5='時'; 0xF6='分'; 0xF7='秒'
}

$fontCollection = New-Object System.Drawing.Text.PrivateFontCollection
try {
    $fontCollection.AddFontFile($FontPath)

    $katakanaBank = New-EmptyBank
    $hiraganaBank = New-EmptyBank

    for($code = 0x20; $code -le 0x7E; $code++) {
        $text = [char]$code
        $glyph = Convert-CharToGlyph -FontCollection $fontCollection -Text $text -FontSize $FontSize -XOffset $XOffset -YOffset $YOffset -Threshold $Threshold
        Set-Glyph -Bank $katakanaBank -Code $code -Glyph $glyph
        Set-Glyph -Bank $hiraganaBank -Code $code -Glyph $glyph
    }

    foreach($entry in $katakanaMap.GetEnumerator()) {
        $glyph = Convert-CharToGlyph -FontCollection $fontCollection -Text $entry.Value -FontSize $FontSize -XOffset $XOffset -YOffset $YOffset -Threshold $Threshold
        Set-Glyph -Bank $katakanaBank -Code ([int]$entry.Key) -Glyph $glyph
    }

    foreach($entry in $hiraganaMap.GetEnumerator()) {
        $glyph = Convert-CharToGlyph -FontCollection $fontCollection -Text $entry.Value -FontSize $FontSize -XOffset $XOffset -YOffset $YOffset -Threshold $Threshold -CompressWide
        Set-Glyph -Bank $hiraganaBank -Code ([int]$entry.Key) -Glyph $glyph
    }

    foreach($entry in $embeddedGlyphMap.GetEnumerator()) {
        $glyph = [byte[]]$entry.Value
        Set-Glyph -Bank $katakanaBank -Code ([int]$entry.Key) -Glyph $glyph
        Set-Glyph -Bank $hiraganaBank -Code ([int]$entry.Key) -Glyph $glyph
    }

    foreach($entry in $generatedSymbolMap.GetEnumerator()) {
        $glyph = Convert-CharToGlyph -FontCollection $fontCollection -Text $entry.Value -FontSize $FontSize -XOffset $XOffset -YOffset $YOffset -Threshold $Threshold -CompressWide
        Set-Glyph -Bank $katakanaBank -Code ([int]$entry.Key) -Glyph $glyph
        Set-Glyph -Bank $hiraganaBank -Code ([int]$entry.Key) -Glyph $glyph
    }

    $rom = New-Object byte[] 8192
    [Array]::Copy($katakanaBank, 0, $rom, 0x0000, 4096)
    [Array]::Copy($hiraganaBank, 0, $rom, 0x1000, 4096)

    $outputDir = Split-Path -Parent $OutputPath
    New-Item -ItemType Directory -Force -Path $outputDir | Out-Null
    [System.IO.File]::WriteAllBytes($OutputPath, $rom)

    if($WriteBankFiles) {
        New-Item -ItemType Directory -Force -Path $fontBuildDir | Out-Null
        [System.IO.File]::WriteAllBytes((Join-Path $fontBuildDir 'kh_dougenzaka16_fontrom_katakana_8x16.bin'), $katakanaBank)
        [System.IO.File]::WriteAllBytes((Join-Path $fontBuildDir 'kh_dougenzaka16_fontrom_hiragana_8x16.bin'), $hiraganaBank)
    }

    Write-Host "Generated $OutputPath ($($rom.Length) bytes)"
    Write-Host "Font source $FontPath"
    Write-Host "Bank 0: 0x0000-0x0FFF katakana/ANK"
    Write-Host "Bank 1: 0x1000-0x1FFF hiragana/ANK"
}
finally {
    $fontCollection.Dispose()
}
