function New-EmptyBank {
    $bank = New-Object byte[] 4096
    for($i = 0; $i -lt $bank.Length; $i++) {
        $bank[$i] = 0x00
    }
    return ,$bank
}

function Set-Glyph {
    param(
        [byte[]]$Bank,
        [int]$Code,
        [byte[]]$Glyph
    )

    if($Code -lt 0 -or $Code -gt 255) {
        throw "Glyph code out of range: $Code"
    }
    if($Glyph.Length -ne 16) {
        throw "Glyph must be exactly 16 bytes: $Code"
    }

    [Array]::Copy($Glyph, 0, $Bank, $Code * 16, 16)
}

function Convert-CharToGlyph {
    param(
        [System.Drawing.Text.PrivateFontCollection]$FontCollection,
        [string]$Text,
        [int]$FontSize,
        [int]$XOffset,
        [int]$YOffset,
        [int]$Threshold,
        [switch]$CompressWide
    )

    $bitmap = New-Object System.Drawing.Bitmap 16, 16, ([System.Drawing.Imaging.PixelFormat]::Format24bppRgb)
    $graphics = [System.Drawing.Graphics]::FromImage($bitmap)
    $font = $null
    try {
        $graphics.Clear([System.Drawing.Color]::White)
        $graphics.PageUnit = [System.Drawing.GraphicsUnit]::Pixel
        $graphics.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::None
        $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::NearestNeighbor
        $graphics.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::Half
        $graphics.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit

        $format = [System.Drawing.StringFormat]::GenericTypographic.Clone()
        $format.FormatFlags = $format.FormatFlags -bor [System.Drawing.StringFormatFlags]::NoClip
        $font = New-Object System.Drawing.Font $FontCollection.Families[0], $FontSize, ([System.Drawing.FontStyle]::Regular), ([System.Drawing.GraphicsUnit]::Pixel)
        $graphics.DrawString($Text, $font, [System.Drawing.Brushes]::Black, ([System.Drawing.PointF]::new($XOffset, $YOffset)), $format)

        $glyph = New-Object byte[] 16
        for($y = 0; $y -lt 16; $y++) {
            $row = 0
            for($x = 0; $x -lt 8; $x++) {
                $on = $false
                if($CompressWide) {
                    foreach($sx in @(($x * 2), ($x * 2 + 1))) {
                        $pixel = $bitmap.GetPixel($sx, $y)
                        if($pixel.R -lt $Threshold -or $pixel.G -lt $Threshold -or $pixel.B -lt $Threshold) {
                            $on = $true
                            break
                        }
                    }
                } else {
                    $pixel = $bitmap.GetPixel($x, $y)
                    if($pixel.R -lt $Threshold -or $pixel.G -lt $Threshold -or $pixel.B -lt $Threshold) {
                        $on = $true
                    }
                }
                if($on) {
                    $row = $row -bor (0x80 -shr $x)
                }
            }
            $glyph[$y] = [byte]$row
        }
        return ,$glyph
    }
    finally {
        if($font -ne $null) {
            $font.Dispose()
        }
        $graphics.Dispose()
        $bitmap.Dispose()
    }
}

